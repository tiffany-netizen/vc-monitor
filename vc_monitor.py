def write_github_summary(
    vc_scan_results: Optional[dict] = None,
    jobs_found: Optional[list] = None,
):
    """Write a markdown summary to $GITHUB_STEP_SUMMARY if running in GitHub Actions."""
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if not summary_path:
        return

    lines = ["## VC Monitor Run Summary\n"]

    if vc_scan_results:
        lines.append("### Portfolio Scan")
        lines.append(f"- VCs scanned: **{vc_scan_results.get('vcs_scanned', 0)}**")
        lines.append(f"- New companies found: **{vc_scan_results.get('new_companies', 0)}** (status: pending)")
        lines.append(f"- Existing companies updated: **{vc_scan_results.get('updated', 0)}**")
        lines.append("")

    if jobs_found is not None:
        lines.append("### Job Scan")
        lines.append(f"- Matching jobs found: **{len(jobs_found)}**")
        if jobs_found:
            lines.append("")
            lines.append("| Title | Company | Stage | VCs |")
            lines.append("|-------|---------|-------|-----|")
            for j in jobs_found[:25]:
                lines.append(
                    f"| {j['title']} | {j['company']} | {j['stage']} | {j['vcs_invested']} |"
                )
            if len(jobs_found) > 25:
                lines.append(f"| ... and {len(jobs_found) - 25} more | | | |")
        lines.append("")

    try:
        with open(summary_path, "a") as f:
            f.write("\n".join(lines) + "\n")
    except Exception as e:
        log.debug(f"Could not write GitHub summary: {e}")


