def discover_careers_pages():
    """For approved companies missing a careers URL, attempt to find one."""
    url = f"{SUPABASE_URL}/vc_portfolio_companies"
    params = {
        "careers_url": "is.null",
        "active": "eq.true",
        "excluded": "eq.false",
        "status": "eq.approved",
        "limit": 1000,
    }
    try:
        resp = requests.get(url, headers=sb.headers, params=params, timeout=15)
        resp.raise_for_status()
        rows = resp.json() if resp.text else []
    except Exception as e:
        log.error(f"Failed to fetch companies for careers discovery: {e}")
        return

    log.info(f"Discovering careers pages for {len(rows)} companies...")

    for row in rows:
        domain = row.get("domain")
        company = row.get("company")
        company_id = row.get("id")

        if not domain:
            continue

        careers_url = find_careers_url(domain)

        if not careers_url:
            log.debug(f"  No careers page: {company} ({domain})")
            continue

        # Detect ATS
        resp = safe_get(careers_url, timeout=10)
        ats_type = ats_slug = None
        if resp:
            ats_type, ats_slug, direct = detect_ats(resp.text, careers_url)
            careers_url = direct or careers_url

        sb.update(
            "vc_portfolio_companies",
            {"id": company_id},
            {"careers_url": careers_url, "ats_type": ats_type, "ats_slug": ats_slug}
        )
        log.info(f"  ✓ {company}: {careers_url}  [ATS: {ats_type or 'unknown'}]")
        time.sleep(0.5)


