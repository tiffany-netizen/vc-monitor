def scrape_greenhouse(slug: str) -> list[dict]:
    """Use Greenhouse public API."""
    url = f"https://boards-api.greenhouse.io/v1/boards/{slug}/jobs?content=true"
    resp = safe_get(url)
    if not resp:
        return []
    try:
        data = resp.json()
        jobs = []
        for j in data.get("jobs", []):
            title = j.get("title", "")

            # Location: prefer offices list, fall back to location field
            location = ", ".join(
                loc.get("name", "") for loc in j.get("offices", []) if loc.get("name")
            ) or j.get("location", {}).get("name", "")

            job_url = j.get("absolute_url", "")

            # Salary from metadata fields
            salary_text = ""
            for meta in j.get("metadata", []):
                name_lower = meta.get("name", "").lower()
                if "salary" in name_lower or "comp" in name_lower or "pay" in name_lower:
                    salary_text = str(meta.get("value") or "")

            # Also check content for salary mention
            content = j.get("content", "") or ""
            if not salary_text:
                m = re.search(
                    r'\$[\d,]+\s*[-–]\s*\$[\d,]+|\$[\d,]+[kK]?\s*[-–]\s*\$[\d,]+[kK]?',
                    content
                )
                if m:
                    salary_text = m.group(0)

            jobs.append({
                "title": title,
                "location": location,
                "url": job_url,
                "salary_text": salary_text,
            })
        return jobs
    except Exception as e:
        log.debug(f"Greenhouse parse error ({slug}): {e}")
        return []


def scrape_lever(slug: str) -> list[dict]:
    """Use Lever public API."""
    url = f"https://api.lever.co/v0/postings/{slug}?mode=json"
    resp = safe_get(url)
    if not resp:
        return []
    try:
        data = resp.json()
        jobs = []
        for j in data:
            title = j.get("text", "")
            cats = j.get("categories", {})
            location = cats.get("location", "") or cats.get("allLocations", [""])[0]
            job_url = j.get("hostedUrl", "")

            salary_text = ""
            for lst in j.get("lists", []):
                lst_text = lst.get("text", "").lower()
                if "salary" in lst_text or "compensation" in lst_text or "pay" in lst_text:
                    salary_text = BeautifulSoup(lst.get("content", ""), "lxml").get_text(" ")

            # Check plain text content
            if not salary_text:
                plain = j.get("description", "") or j.get("descriptionPlain", "") or ""
                m = re.search(
                    r'\$[\d,]+\s*[-–]\s*\$[\d,]+|\$[\d,]+[kK]?\s*[-–]\s*\$[\d,]+[kK]?',
                    plain
                )
                if m:
                    salary_text = m.group(0)

            jobs.append({
                "title": title,
                "location": location,
                "url": job_url,
                "salary_text": salary_text,
            })
        return jobs
    except Exception as e:
        log.debug(f"Lever parse error ({slug}): {e}")
        return []


def scrape_ashby(slug: str) -> list[dict]:
    """Use Ashby HQ public GraphQL endpoint."""
    url = "https://jobs.ashbyhq.com/api/non-user-graphql"
    query = {
        "operationName": "ApiJobBoardWithTeams",
        "variables": {"organizationHostedJobsPageName": slug},
        "query": """
            query ApiJobBoardWithTeams($organizationHostedJobsPageName: String!) {
              jobBoard: jobBoardWithTeams(
                organizationHostedJobsPageName: $organizationHostedJobsPageName
              ) {
                jobPostings {
                  id
                  title
                  isRemote
                  locationName
                  compensationTierSummary
                  externalLink
                  publishedDate
                }
              }
            }
        """,
    }
