def enrich_stages():
    """
    For companies missing a stage, attempt Crunchbase lookup.
    Companies found to be Series D+ are marked excluded=True.
    """
    # Get companies with no stage, active
    url = f"{SUPABASE_URL}/vc_portfolio_companies"
    params = {
        "stage": "is.null",
        "active": "eq.true",
        "limit": 1000,
    }
    try:
        resp = requests.get(url, headers=sb.headers, params=params, timeout=15)
        resp.raise_for_status()
        rows = resp.json() if resp.text else []
    except Exception as e:
        log.error(f"Failed to fetch companies for stage enrichment: {e}")
        return

    log.info(f"Enriching funding stages for {len(rows)} companies...")

    for row in rows:
        company_id = row.get("id")
        company = row.get("company")

        if not company:
            continue

        stage = lookup_stage_crunchbase(company)
        if not stage:
            continue

        excluded = not stage_qualifies(stage)
        sb.update(
            "vc_portfolio_companies",
            {"id": company_id},
            {"stage": stage, "excluded": excluded}
        )
        if excluded:
            log.info(f"  Excluding {company} — stage: {stage}")

        time.sleep(0.3)  # polite crawling


