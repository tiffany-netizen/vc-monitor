def scan_all_jobs() -> list[dict]:
    """Scan jobs for approved, active portfolio companies."""
    url = f"{SUPABASE_URL}/vc_portfolio_companies"
    params = {
        "active": "eq.true",
        "excluded": "eq.false",
        "status": "eq.approved",
        "careers_url": "not.is.null",
        "limit": 1000,
    }
    try:
        resp = requests.get(url, headers=sb.headers, params=params, timeout=15)
        resp.raise_for_status()
        rows = resp.json() if resp.text else []
    except Exception as e:
        log.error(f"Failed to fetch companies for job scanning: {e}")
        return []

    log.info(f"Scanning jobs for {len(rows)} companies...")
    now = datetime.utcnow().isoformat()
    matching = []

    for co in rows:
        stage = co.get("stage") or ""
        if stage and not stage_qualifies(stage):
            continue

        jobs = get_jobs_for_company(co)
        vc_names = co.get("vc_names") or []

        for job in jobs:
            title = job.get("title", "").strip()
            location = job.get("location", "").strip()
            salary_text = job.get("salary_text", "").strip()
            job_url = job.get("url", "").strip()

            if not title_matches(title):
                continue
            if not is_us_location(location):
                continue
            if not salary_qualifies(salary_text):
                continue

            salary_min = None
            if salary_text:
                vals = re.findall(r"\$?([\d,]+)[kK]?", salary_text.replace(",", ""))
                nums = []
                for v in vals:
                    n = int(v)
                    if "k" in salary_text.lower() and n < 10_000:
                        n *= 1_000
                    if n >= 10_000:
                        nums.append(n)
                salary_min = min(nums) if nums else None

            matching.append({
                "title": title,
                "company": co["company"],
                "stage": stage or "Unknown",
                "vcs_invested": " | ".join(vc_names),
                "location": location or "Not specified",
                "salary": salary_text or "Not listed",
                "url": job_url,
                "first_seen": now,
            })

            # Check if job already exists in vc_jobs
            existing = sb.get_by_url(job_url, "vc_jobs")
            if existing:
                sb.update(
                    "vc_jobs",
                    {"url": job_url},
                    {"last_seen": now, "active": True}
                )
            else:
                sb.insert(
                    "vc_jobs",
                    {
                        "company_id": co["id"],
                        "title": title,
                        "url": job_url,
                        "location": location,
                        "salary_text": salary_text,
                        "salary_min": salary_min,
                        "vc_names": vc_names,
                        "source": "vc_monitor",
                        "first_seen": now,
                        "last_seen": now,
                        "active": True,
                    }
                )

            # Cross-post to the main jobs table so it appears in the dashboard
            existing_main = sb.get_by_url(job_url, "jobs")
            if existing_main:
                sb.update("jobs", {"url": job_url}, {"last_seen": now})
            else:
                sb.insert(
                    "jobs",
                    {
                        "company_name": co["company"],
                        "title": title,
                        "url": job_url,
                        "source": "vc_monitor",
                        "first_seen": now,
                        "last_seen": now,
                        "status": "new",
                    }
                )

        time.sleep(0.5)

    log.info(f"Found {len(matching)} matching jobs")
    return matching


