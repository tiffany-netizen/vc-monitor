def lookup_stage_crunchbase(company_name: str) -> Optional[str]:
    """
    Query Crunchbase's public autocomplete API for last known funding stage.
    Returns e.g. 'series_b', 'seed', etc.  or None on failure.
    """
    url = "https://www.crunchbase.com/v4/data/autocompletes"
    params = {
        "query": company_name,
        "collection_ids": "organizations",
        "limit": 3,
    }
    try:
        resp = requests.get(url, params=params, headers=HEADERS, timeout=10)
        for entity in resp.json().get("entities", []):
            props = entity.get("properties", {})
            stage = (
                props.get("funding_stage", {}).get("value")
                or props.get("last_funding_type", {}).get("value")
            )
            if stage:
                return stage.lower().replace("_", " ")
    except Exception:
        pass
    return None


