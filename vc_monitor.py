def title_matches(title: str) -> bool:
    """Return True if the job title matches any target role."""
    t = title.lower().strip()

    # Reject anything that looks like page content rather than a job title:
    # real job titles are short and don't contain URLs, cookie language, etc.
    if len(t) > 100:
        return False
    junk_phrases = [
        'cookie', 'privacy policy', 'gdpr', 'javascript:', 'visit site',
        'read more', 'learn more', 'sign up', 'log in', 'subscribe',
    ]
    for phrase in junk_phrases:
        if phrase in t:
            return False

    # Word-boundary match (not bare substring) to avoid "cfos", "office of cfo", etc.
    patterns = [
        r'\bcfo\b', r'\bcoo\b', r'\bcro\b',
        r'\bchief of staff\b',
        r'\bchief financial officer\b',
        r'\bchief operating officer\b',
        r'\bchief revenue officer\b',
        r'\b(vp|vice president) of (finance|operations|ops|revenue operations)\b',
        r'\b(svp|senior vice president) of (finance|operations|ops)\b',
        r'\bdirector of (finance|technical accounting|accounting)\b',
        r'\bhead of (finance|operations|ops|fp&a|strategic finance|'
        r'revenue cycle|accounting operations|revenue cycle management)\b',
        r'\bhead of finance and operations\b',
        r'\bhead of ops and finance\b',
    ]
    for pat in patterns:
        if re.search(pat, t):
            return True
    return False


def is_us_location(location: str) -> bool:
    """Return True if the location is US-based or unspecified."""
    if not location or not location.strip():
        return True  # include unspecified (could be remote)

    loc = location.lower()

    non_us_keywords = [
        'london', ' uk', 'united kingdom', 'england', 'canada', 'toronto',
        'vancouver', 'india', 'bangalore', 'bengaluru', 'mumbai', 'hyderabad',
        'australia', 'sydney', 'melbourne', 'germany', 'berlin', 'france',
        'paris', 'singapore', 'hong kong', 'mexico', 'brazil', 'netherlands',
        'amsterdam', 'sweden', 'stockholm', 'ireland', 'dublin', 'israel',
        'tel aviv', 'spain', 'madrid', 'barcelona', 'poland', 'warsaw',
        'japan', 'tokyo', 'korea', 'seoul', 'china', 'beijing', 'shanghai',
    ]
    for kw in non_us_keywords:
        if kw in loc:
            return False

    return True  # default include


def salary_qualifies(salary_text: str) -> bool:
    """Return True if salary meets minimum or if salary is not listed."""
    if not salary_text or not salary_text.strip():
        return True

    text = salary_text.replace(',', '').lower()
    matches = re.findall(r'\$?(\d+(?:\.\d+)?)([km]?)', text)

    values = []
    for num_str, suffix in matches:
        val = float(num_str)
        if suffix == 'k':
            val *= 1_000
        elif suffix == 'm':
            val *= 1_000_000
        if val >= 10_000:  # plausible annual salary
            values.append(int(val))

    if not values:
        return True  # can't parse, include it

    return min(values) >= MIN_SALARY


def stage_qualifies(stage: str) -> bool:
    """True only for Series A/B/C. Unknown/unconfirmed stages are excluded."""
    if not stage or stage.lower().strip() in ("", "unknown", "not specified"):
        return False
    s = stage.lower().strip()
    for ex in EXCLUDE_STAGES:
        if ex in s:
            return False
    for tgt in TARGET_STAGES:
        if tgt in s:
            return True
    return False  # unknown stage: exclude


