def test_ats(specs: list[str]):
    """
    Quick-test specific ATS slugs without database.
    Format: ats_type:slug  e.g.  greenhouse:lever  lever:levels  ashby:ashbyhq
    """
    for spec in specs:
        parts = spec.split(":", 1)
        if len(parts) != 2:
            print(f"Bad spec: {spec}  (use ats_type:slug)")
            continue
        ats_type, slug = parts
        print(f"\n{'─'*55}")
        print(f"Testing {ats_type.upper()} slug: {slug}")
        print(f"{'─'*55}")

        if ats_type == "greenhouse":
            jobs = scrape_greenhouse(slug)
        elif ats_type == "lever":
            jobs = scrape_lever(slug)
        elif ats_type == "ashby":
            jobs = scrape_ashby(slug)
        else:
            print(f"Unknown ATS type: {ats_type}")
            continue

        matches = [j for j in jobs if title_matches(j["title"]) and is_us_location(j["location"])]
        print(f"Total jobs: {len(jobs)}  |  Matching roles: {len(matches)}")
        for j in matches:
            print(f"  • {j['title']}  [{j['location']}]  {j['salary_text'] or '(no salary)'}  {j['url']}")


