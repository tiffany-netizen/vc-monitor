def scrape_vc_portfolio_static(vc: dict) -> list[dict]:
    """
    Scrape a static VC portfolio page.
    Returns [{company_name, domain, stage, detail_url}].
    """
    url = vc["portfolio_url"]
    resp = safe_get(url)
    if not resp:
        log.warning(f"  Could not fetch {url}")
        return []

    soup = BeautifulSoup(resp.text, "lxml")
    vc_domain = get_domain(url)
    seen_domains = set()
    companies = []

    skip_domains = {
        "twitter.com", "x.com", "linkedin.com", "facebook.com",
        "instagram.com", "youtube.com", "crunchbase.com", "pitchbook.com",
        "medium.com", "techcrunch.com",
    }

    junk_names = {
        "exit", "visit site", "visit", "view", "learn more",
        "read more", "lp login", "sign in", "log in", "sign up",
        "contact", "contact us", "about", "about us", "home",
        "back to top", "subscribe", "newsletter", "blog",
        "portfolio", "team", "careers", "press", "news",
        "privacy", "terms", "cookie", "menu", "close",
        "view open roles here.", "our portfolio companies.",
        "portfolio jobs", "see all", "view all", "show more",
        "load more", "explore", "apply now",
    }
    seen_names = set()

    for a in soup.find_all("a", href=True):
        text = a.get_text(" ", strip=True)
        if not text or len(text) < 2 or len(text) > 80:
            continue
        if text.lower().rstrip(".") in junk_names:
            continue
        if len(text.split()) > 8:
            continue

        full_url = urljoin(url, a["href"])
        domain = get_domain(full_url)

        if not domain or domain == vc_domain:
            continue
        if domain in skip_domains:
            continue
        if domain in seen_domains:
            continue
        if any(s in full_url.lower() for s in ["mailto:", "tel:", "#"]):
            continue

        name_key = text.lower().strip()
        if name_key in seen_names:
            continue

        seen_domains.add(domain)
        seen_names.add(name_key)
        companies.append({
            "company_name": text,
            "domain": domain,
            "stage": None,
            "detail_url": full_url,
        })

    return companies


async def scrape_vc_portfolio_playwright(vc: dict) -> list[dict]:
    """
    Playwright-based scraper for JS-rendered VC portfolio pages.
    Uses multiple extraction strategies:
      1. Intercept XHR/fetch responses that may contain portfolio data
      2. Scroll to bottom to trigger lazy loading
      3. Extract from links, cards, grid items, and logo containers
    Falls back to static scraper if Playwright is not installed.
    """
    try:
        from playwright.async_api import async_playwright
    except ImportError:
        log.warning(
            f"  Playwright not installed — using static fallback for {vc['name']}.\n"
            "  Install with: pip install playwright && playwright install chromium"
        )
        return scrape_vc_portfolio_static(vc)

    url = vc["portfolio_url"]
    vc_domain = get_domain(url)
    skip_domains = {
        "twitter.com", "x.com", "linkedin.com", "facebook.com",
        "instagram.com", "youtube.com", "crunchbase.com", "pitchbook.com",
        "medium.com", "techcrunch.com", "github.com", "google.com",
        "apple.com", "apps.apple.com", "play.google.com",
    }
    companies = []
    api_companies = []  # companies found via intercepted API responses

    async with async_playwright() as pw:
        browser = await pw.chromium.launch(headless=True)
        page = await browser.new_page(
            user_agent=HEADERS["User-Agent"],
            viewport={"width": 1280, "height": 900},
        )

        # Strategy 1: Intercept network responses for portfolio API data
        async def handle_response(response):
            try:
                content_type = response.headers.get("content-type", "")
                if "json" not in content_type:
                    return
                if response.status != 200:
                    return
                body = await response.text()
                if len(body) < 100 or len(body) > 5_000_000:
                    return
                data = json.loads(body)
                _extract_companies_from_api(data, api_companies, vc_domain, skip_domains)
            except Exception:
                pass

        page.on("response", handle_response)

        try:
            await page.goto(url, wait_until="networkidle", timeout=45_000)
            await page.wait_for_timeout(2_000)

            # Strategy 2: Scroll to bottom to trigger lazy loading
            await _scroll_to_bottom(page)
            await page.wait_for_timeout(2_000)

            # Strategy 3: Extract from DOM — links, cards, grid items
            links_data = await page.evaluate("""
                () => {
                    const results = [];
                    const seen = new Set();

                    // Helper: extract domain from URL
                    function getDomain(url) {
                        try { return new URL(url).hostname.replace(/^www\\./, ''); }
                        catch { return null; }
                    }

                    // Helper: find stage text near an element
                    function findStage(el) {
                        const container = el.closest('[class]') || el.parentElement;
                        if (!container) return null;
                        const text = (container.innerText || '').toLowerCase();
                        const m = text.match(
                            /\\b(pre-?seed|seed|series\\s*[a-d])\\b/i
                        );
                        return m ? m[1].trim() : null;
                    }

                    // Pass 1: External links (original approach, still valuable)
                    document.querySelectorAll('a[href]').forEach(a => {
                        const text = (a.innerText || a.textContent || '').trim();
                        const href = a.href;
                        if (!text || text.length < 2 || text.length > 80) return;
                        const domain = getDomain(href);
                        if (!domain || seen.has(domain)) return;
                        seen.add(domain);
                        results.push({
                            text, href, domain,
                            stage: findStage(a),
                            source: 'link'
                        });
                    });

                    // Pass 2: Cards / grid items that may contain company info
                    // Look for repeated sibling elements (portfolio grid pattern)
                    const cardSelectors = [
                        '[class*="portfolio"] [class*="item"]',
                        '[class*="portfolio"] [class*="card"]',
                        '[class*="company"]', '[class*="startup"]',
                        '[class*="grid"] > div', '[class*="grid"] > a',
                        '[class*="logo"]', '[class*="brand"]',
                        '[data-company]', '[data-name]',
                    ];
                    for (const sel of cardSelectors) {
                        document.querySelectorAll(sel).forEach(card => {
                            // Get company name from heading, alt text, or card text
                            const heading = card.querySelector('h2,h3,h4,h5,strong,[class*="name"],[class*="title"]');
                            const img = card.querySelector('img[alt]');
                            let name = '';
                            if (heading && heading.innerText) name = heading.innerText.trim();
                            else if (img && img.alt && img.alt.length > 1 && img.alt.length < 80) name = img.alt.trim();
                            else if (card.innerText) {
                                const t = card.innerText.trim();
                                if (t.length > 1 && t.length < 80 && !t.includes('\\n')) name = t;
                            }
                            if (!name || name.length < 2) return;

                            // Get URL from link in card or card itself
                            const link = card.tagName === 'A' ? card : card.querySelector('a[href]');
                            const href = link ? link.href : '';
                            const domain = href ? getDomain(href) : null;

                            if (domain && !seen.has(domain)) {
                                seen.add(domain);
                                results.push({
                                    text: name, href, domain,
                                    stage: findStage(card),
                                    source: 'card'
                                });
                            } else if (!domain && name.length > 2) {
                                // Company name without link — still useful
                                results.push({
                                    text: name, href: '', domain: null,
                                    stage: findStage(card),
                                    source: 'card_nolink'
                                });
                            }
                        });
                    }

                    return results;
                }
            """)

            # Junk text patterns to skip (nav elements, exit labels, etc.)
            junk_names = {
                "exit", "visit site", "visit", "view", "learn more",
                "read more", "lp login", "sign in", "log in", "sign up",
                "contact", "contact us", "about", "about us", "home",
                "back to top", "subscribe", "newsletter", "blog",
                "portfolio", "team", "careers", "press", "news",
                "privacy", "terms", "cookie", "menu", "close",
                "view open roles here.", "our portfolio companies.",
                "portfolio jobs", "see all", "view all", "show more",
                "load more", "explore", "apply now",
            }

            seen_domains = set()
            seen_names = set()
            for item in links_data:
                text = (item.get("text") or "").strip()
                href = item.get("href") or ""
                stage = item.get("stage")
                domain = item.get("domain") or (get_domain(href) if href else None)

                if not text or len(text) < 2 or len(text) > 80:
                    continue
                # Skip junk nav/label text
                if text.lower().rstrip(".") in junk_names:
                    continue
                # Skip if text looks like a sentence or description (has too many words)
                if len(text.split()) > 8:
                    continue
                # Must have a domain; entries without one are unusable
                if not domain:
                    continue
                if domain == vc_domain:
                    continue
                if domain in skip_domains:
                    continue
                if domain in seen_domains:
                    continue
                if any(s in href.lower() for s in ["mailto:", "tel:", "javascript:"]):
                    continue
                # Skip duplicate company names (catches same company from different elements)
                name_key = text.lower().strip()
                if name_key in seen_names:
                    continue

                seen_domains.add(domain)
                seen_names.add(name_key)

                companies.append({
                    "company_name": text,
                    "domain": domain,
                    "stage": stage,
                    "detail_url": href,
                })

        except Exception as e:
            log.error(f"  Playwright error on {url}: {e}")
        finally:
            await browser.close()

    # Merge API-discovered companies (higher confidence)
    seen_domains = {c["domain"] for c in companies if c.get("domain")}
    for ac in api_companies:
        if ac.get("domain") and ac["domain"] not in seen_domains:
            companies.append(ac)
            seen_domains.add(ac["domain"])

    return companies


async def _scroll_to_bottom(page, max_scrolls: int = 10):
    """Scroll page to bottom incrementally to trigger lazy loading."""
    for _ in range(max_scrolls):
        prev_height = await page.evaluate("document.body.scrollHeight")
        await page.evaluate("window.scrollTo(0, document.body.scrollHeight)")
        await page.wait_for_timeout(800)
        new_height = await page.evaluate("document.body.scrollHeight")
        if new_height == prev_height:
            break


def _extract_companies_from_api(
    data, results: list, vc_domain: str, skip_domains: set
):
    """
    Recursively search JSON API response data for portfolio company info.
    Many VC sites fetch portfolio data from a CMS API (Contentful, Sanity, etc.).
    """
    if isinstance(data, list):
        for item in data:
            _extract_companies_from_api(item, results, vc_domain, skip_domains)
    elif isinstance(data, dict):
        # Heuristic: dict with name/company/title + url/website/domain fields
        name_keys = {"name", "company", "company_name", "title", "companyName"}
        url_keys = {"url", "website", "domain", "href", "link", "websiteUrl", "companyUrl"}

        name_val = None
        url_val = None
        for k, v in data.items():
            if k.lower() in {nk.lower() for nk in name_keys} and isinstance(v, str) and 2 < len(v) < 80:
                name_val = v
            if k.lower() in {uk.lower() for uk in url_keys} and isinstance(v, str) and ("." in v or "http" in v):
                url_val = v

        if name_val and url_val:
            if not url_val.startswith("http"):
                url_val = f"https://{url_val}"
            domain = get_domain(url_val)
            if domain and domain != vc_domain and domain not in skip_domains:
                results.append({
                    "company_name": name_val,
                    "domain": domain,
                    "stage": data.get("stage") or data.get("funding_stage"),
                    "detail_url": url_val,
                })
                return  # don't recurse into this object's children

        # Recurse into nested objects/arrays
        for v in data.values():
            if isinstance(v, (dict, list)):
                _extract_companies_from_api(v, results, vc_domain, skip_domains)


