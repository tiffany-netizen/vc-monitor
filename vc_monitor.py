class SupabaseClient:
    """Simple Supabase REST client for VC monitor operations."""

    def __init__(self, url: str = SUPABASE_URL, key: str = SUPABASE_KEY):
        self.url = url
        self.headers = {
            "apikey": key,
            "Authorization": f"Bearer {key}",
            "Content-Type": "application/json",
        }

    def select(self, table: str, query: str = "", limit: int = 1000) -> list[dict]:
        """GET from table with optional filter query."""
        url = f"{self.url}/{table}"
        params = {"limit": limit}
        if query:
            params["select"] = query
        try:
            resp = requests.get(url, headers=self.headers, params=params, timeout=15)
            resp.raise_for_status()
            return resp.json() if resp.text else []
        except Exception as e:
            log.debug(f"Supabase SELECT {table} failed: {e}")
            return []

    def select_where(self, table: str, filters: dict, limit: int = 1000) -> list[dict]:
        """GET with WHERE conditions (filter via query params)."""
        url = f"{self.url}/{table}"
        params = {"limit": limit}
        for key, val in filters.items():
            if isinstance(val, bool):
                params[f"{key}=eq.{str(val).lower()}"] = None
            elif isinstance(val, str):
                params[f"{key}=eq.{val}"] = None
            else:
                params[f"{key}=eq.{val}"] = None

        try:
            resp = requests.get(url, headers=self.headers, params=params, timeout=15)
            resp.raise_for_status()
            return resp.json() if resp.text else []
        except Exception as e:
            log.debug(f"Supabase SELECT {table} with filters failed: {e}")
            return []

    def insert(self, table: str, data: dict | list[dict]) -> bool:
        """POST to insert new rows."""
        url = f"{self.url}/{table}"
        try:
            headers = self.headers.copy()
            headers["Prefer"] = "return=minimal"
            resp = requests.post(url, json=data, headers=headers, timeout=15)
            resp.raise_for_status()
            return True
        except Exception as e:
            log.warning(f"Supabase INSERT {table} failed: {e}")
            try:
                log.warning(f"  Response body: {resp.text[:500]}")
            except Exception:
                pass
            return False

    def upsert(self, table: str, data: dict | list[dict], on_conflict: str = "id") -> bool:
        """POST with upsert (merge on conflict)."""
        url = f"{self.url}/{table}"
        try:
            headers = self.headers.copy()
            headers["Prefer"] = "resolution=merge-duplicates,return=minimal"
            resp = requests.post(url, json=data, headers=headers, timeout=15)
            resp.raise_for_status()
            return True
        except Exception as e:
            log.warning(f"Supabase UPSERT {table} failed: {e}")
            try:
                log.warning(f"  Response body: {resp.text[:500]}")
            except Exception:
                pass
            return False

    def update(self, table: str, filters: dict, data: dict) -> bool:
        """PATCH to update rows matching filters."""
        url = f"{self.url}/{table}"
        # Build filter query string: key=eq.value
        filter_parts = []
        for k, v in filters.items():
            if isinstance(v, bool):
                filter_parts.append(f"{k}=eq.{str(v).lower()}")
            else:
                filter_parts.append(f"{k}=eq.{v}")
        filter_query = "&".join(filter_parts)

        try:
            headers = self.headers.copy()
            headers["Prefer"] = "return=minimal"
            full_url = f"{url}?{filter_query}" if filter_query else url
            resp = requests.patch(full_url, json=data, headers=headers, timeout=15)
            resp.raise_for_status()
            return True
        except Exception as e:
            log.warning(f"Supabase UPDATE {table} failed: {e}")
            try:
                log.warning(f"  Response body: {resp.text[:500]}")
                log.warning(f"  PATCH payload: {json.dumps(data)[:500]}")
                log.warning(f"  PATCH URL: {full_url}")
            except Exception:
                pass
            return False

    def get_by_domain(self, domain: str) -> Optional[dict]:
        """Get portfolio company by domain."""
        url = f"{self.url}/vc_portfolio_companies?domain=eq.{domain}&limit=1"
        try:
            resp = requests.get(url, headers=self.headers, timeout=15)
            resp.raise_for_status()
            data = resp.json()
            return data[0] if data else None
        except Exception as e:
            log.debug(f"GET company by domain failed: {e}")
            return None

    def get_by_url(self, url_val: str, table: str = "vc_jobs") -> Optional[dict]:
        """Get job by URL."""
        url = f"{self.url}/{table}?url=eq.{url_val}&limit=1"
        try:
            resp = requests.get(url, headers=self.headers, timeout=15)
            resp.raise_for_status()
            data = resp.json()
            return data[0] if data else None
        except Exception as e:
            log.debug(f"GET by url failed: {e}")
            return None


